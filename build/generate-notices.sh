#!/usr/bin/env bash
# Generates THIRD-PARTY-NOTICES.txt from third-party/<component>/{METADATA,LICENSE[,NOTICE]}.
# The output is never edited by hand: change the inputs and re-run.
#   build/generate-notices.sh          regenerate the file
#   build/generate-notices.sh --check  fail if the committed file is out of date (CI gate)
set -euo pipefail
export LC_ALL=C  # stable component order on every machine

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/THIRD-PARTY-NOTICES.txt"
rule="================================================================================"

generate() {
  echo "ZeroDep third-party notices"
  echo
  echo "ZeroDep is licensed under the Apache License 2.0 (see LICENSE). It has no package"
  echo "dependencies; it includes material from the third parties listed below, each under"
  echo "its own licence. This file is generated by build/generate-notices.sh."
  local dir
  for dir in "$root"/third-party/*/; do
    [ -f "$dir/METADATA" ] && [ -f "$dir/LICENSE" ] || {
      echo "error: $dir needs METADATA and LICENSE" >&2; exit 1; }
    echo
    echo "$rule"
    cat "$dir/METADATA"
    echo "$rule"
    echo
    cat "$dir/LICENSE"
    if [ -f "$dir/NOTICE" ]; then
      echo
      echo "--- NOTICE ---"
      cat "$dir/NOTICE"
    fi
  done
}

if [ "${1:-}" = "--check" ]; then
  if ! generate | diff -q - "$out" > /dev/null; then
    echo "error: THIRD-PARTY-NOTICES.txt is out of date; run build/generate-notices.sh" >&2
    exit 1
  fi
else
  generate > "$out"
fi
